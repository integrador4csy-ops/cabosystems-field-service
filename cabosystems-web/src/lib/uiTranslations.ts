export type TranslationParams = Record<string, string | number>;
export type Translator = (key: string, params?: TranslationParams) => string;

const SPANISH_UI_OVERRIDES: Record<string, string> = { Preview: 'Vista previa', 'Avatar Preview': 'Vista previa de la foto', Offline: 'Desconectado' };

export function interpolate(text: string, params?: TranslationParams): string {
  return params ? text.replace(/\{(\w+)\}/g, (match, key: string) => String(params[key] ?? match)) : text;
}

export function translateUiText(text: string, language: 'es' | 'en', params?: TranslationParams): string {
  return interpolate(language === 'en' ? UI_TRANSLATIONS[text] ?? text : SPANISH_UI_OVERRIDES[text] ?? text, params);
}

export function getLocale(language: 'es' | 'en'): string {
  return language === 'en' ? 'en-US' : 'es-MX';
}

