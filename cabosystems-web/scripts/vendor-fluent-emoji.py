import base64, hashlib, io, json, re, tarfile, urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = '@lobehub/fluent-emoji-3d'
VERSION = '1.1.0'
def fetch(url):
    with urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent': 'CaboSystems-asset-import'}), timeout=90) as response:
        return response.read()
metadata = json.loads(fetch(f'https://registry.npmjs.org/@lobehub%2ffluent-emoji-3d/{VERSION}'))
output = ROOT / 'public' / 'emoji' / 'fluent-3d'
output.mkdir(parents=True, exist_ok=True)
archive = fetch(metadata['dist']['tarball'])
assert metadata['dist']['integrity'] == 'sha512-' + base64.b64encode(hashlib.sha512(archive).digest()).decode(), 'Package integrity mismatch'
codes = []
with tarfile.open(fileobj=io.BytesIO(archive), mode='r:gz') as package:
    for member in package.getmembers():
        if not member.isfile():
            continue
        name = Path(member.name).name
        if re.fullmatch(r'[0-9a-f]+(?:-[0-9a-f]+)*\.webp', name):
            contents = package.extractfile(member).read()
            (output / name).write_bytes(contents)
            codes.append(name.removesuffix('.webp'))
        elif name.upper() in ('LICENSE', 'LICENSE.MD', 'LICENSE.TXT'):
            (output / 'LICENSE-package.txt').write_bytes(package.extractfile(member).read())
assert len(codes) > 1000, f'Unexpected asset count: {len(codes)}'
(output / 'LICENSE-Microsoft.txt').write_bytes(fetch('https://raw.githubusercontent.com/microsoft/fluentui-emoji/main/LICENSE'))
(output / 'NOTICE.md').write_text(f'''# Fluent Emoji 3D\n\nArtwork: Microsoft Fluent Emoji (MIT).\nSource: https://github.com/microsoft/fluentui-emoji\nWebP distribution: {PACKAGE} {metadata['version']} (LobeHub, MIT).\nSource: https://github.com/lobehub/fluent-emoji\nTarball: {metadata['dist']['tarball']}\nIntegrity: {metadata['dist']['integrity']}\n\nBoth license notices are included in this directory.\n''', encoding='utf-8')
manifest = ROOT / 'src' / 'lib' / 'fluentEmojiAssets.ts'
manifest.write_text('// Generated by scripts/vendor-fluent-emoji.py; Microsoft Fluent Emoji 3D.\nexport const FLUENT_EMOJI_CODES = new Set<string>(' + json.dumps(sorted(set(codes))) + ');\n' + "\nexport const FLUENT_EMOJI_FILES = new Map(Array.from(FLUENT_EMOJI_CODES, (file) => [file.split('-').filter((point) => point !== 'fe0f').map((point) => Number.parseInt(point, 16).toString(16)).join('-'), file]));\n", encoding='utf-8')
print(f'Vendored {len(set(codes))} Fluent Emoji 3D assets, package {metadata["version"]}, {sum(p.stat().st_size for p in output.glob("*.webp")) / 1024 / 1024:.1f} MiB.')
