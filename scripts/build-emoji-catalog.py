"""Build searchable Unicode 17 / CLDR 48 data. Downloads data only, never code."""
import json
import re
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1] / 'cabosystems-web'
def fetch(url):
    return urllib.request.urlopen(url, timeout=60).read().decode('utf-8')

def normal(value):
    return value.replace('\ufe0f', '')

names, words = {}, {}
for folder in ('annotations', 'annotationsDerived'):
    xml = fetch(f'https://raw.githubusercontent.com/unicode-org/cldr/release-48/common/{folder}/es.xml')
    for annotation in ET.fromstring(xml).iter('annotation'):
        key = normal(annotation.attrib['cp'])
        target = names if annotation.attrib.get('type') == 'tts' else words
        target[key] = annotation.text or ''

groups = {'Smileys & Emotion':'smileys', 'People & Body':'people', 'Component':'people',
          'Animals & Nature':'nature', 'Food & Drink':'food', 'Travel & Places':'travel',
          'Activities':'activities', 'Objects':'objects', 'Symbols':'symbols', 'Flags':'flags'}
entries = []
for line in fetch('https://unicode.org/Public/17.0.0/emoji/emoji-test.txt').splitlines():
    if line.startswith('# group: '):
        category = groups[line.removeprefix('# group: ')]
    match = re.match(r'^([0-9A-F ]+)\s*; (?:fully-qualified|component)\s*# (\S+) E[\d.]+ (.+)$', line)
    if not match:
        continue
    _, emoji, english = match.groups()
    key = normal(emoji)
    entries.append([emoji, names.get(key, english), english, words.get(key, ''), category])

output = '// Generated by scripts/build-emoji-catalog.py. Unicode 17.0 / CLDR 48.\n'
output += 'export type EmojiCategory = "smileys" | "people" | "nature" | "food" | "travel" | "activities" | "objects" | "symbols" | "flags";\n'
output += 'export const EMOJI_CATALOG: readonly (readonly [string, string, string, string, EmojiCategory])[] = '
output += json.dumps(entries, ensure_ascii=False, separators=(',', ':')) + ';\n'
(ROOT / 'src/lib/emojiCatalog.ts').write_text(output, encoding='utf-8')
license_dir = ROOT / 'public/emoji'
(license_dir / 'LICENSE-Unicode.txt').write_text(fetch('https://raw.githubusercontent.com/unicode-org/cldr/release-48/LICENSE'), encoding='utf-8')
print(f'Generated {len(entries)} searchable emoji, including skin tones, flags and sequences.')
