"""Bundle the exact web Fluent artwork/catalog in Expo; no remote image dependency."""
import shutil
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
web = ROOT / 'cabosystems-web'
mobile = ROOT / 'cabosystems-mobile'
target = mobile / 'assets/emoji/fluent-3d'
target.mkdir(parents=True, exist_ok=True)
entries = {}
for source in sorted((web / 'public/emoji/fluent-3d').iterdir()):
    if source.suffix not in ('.webp', '.txt', '.md'):
        continue
    # Metro enumerates every sibling for each asset lookup. Small deterministic
    # buckets avoid quadratic scanning of thousands of files in a flat folder.
    bucket = hashlib.sha256(source.name.encode('utf-8')).hexdigest()[:2] if source.suffix == '.webp' else ''
    destination = target / bucket / source.name
    destination.parent.mkdir(parents=True, exist_ok=True)
    if not destination.exists() or destination.stat().st_mtime_ns != source.stat().st_mtime_ns:
        shutil.copy2(source, destination)
    if source.suffix == '.webp':
        key = '-'.join(format(int(part, 16), 'x') for part in source.stem.split('-') if part != 'fe0f')
        entries[key] = f"  '{key}': require('../assets/emoji/fluent-3d/{bucket}/{source.name}'),"
        legacy = target / source.name
        # Remove only byte-identical flat copies made by the previous generator.
        if legacy.is_file() and legacy.read_bytes() == source.read_bytes():
            legacy.unlink()
(mobile / 'lib/fluentEmojiAssets.ts').write_text('// Generated by scripts/sync-mobile-chat-emoji.py.\nexport const FLUENT_EMOJI_ASSETS: Record<string, number> = {\n' + '\n'.join(entries.values()) + '\n};\n', encoding='utf-8')
shutil.copy2(web / 'src/lib/emojiCatalog.ts', mobile / 'lib/emojiCatalog.ts')
shutil.copy2(web / 'public/emoji/LICENSE-Unicode.txt', target.parent / 'LICENSE-Unicode.txt')
print(f'Bundled {len(entries)} unique Fluent image mappings and the complete Unicode catalog in Expo.')
